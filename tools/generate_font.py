def build():
    patterns = {k: v.split('/') for k, v in PATTERNS.items()}
    for char in 'áčďéěíňóřšťúůýžÁČĎÉĚÍŇÓŘŠŤÚŮÝŽäöüÄÖÜľĺŕĽĹŔ':
        base, mark = unicodedata.normalize('NFD', char)
        rows = patterns[base]
        width = max(3, len(rows[0]))
        if char.isupper():
            # Zachování příčky i patky v pěti řádcích pod znaménkem.
            body = [rows[i] for i in (0, 1, 3, 5, 6)]
        else:
            body = rows[2:7]
        body = [row.center(width, '0') for row in body]
        marks = {
            '\u0301': ['001', '010'], '\u030c': ['101', '010'],
            '\u030a': ['010', '101', '010'], '\u0308': ['101', '000'],
        }[mark]
        accent = [row.center(width, '0') for row in marks]
        patterns[char] = accent + ['0' * width] * (3 - len(accent)) + body
    # Česká ď a ť mají boční háček, nikoli háček nad obloučkem.
    patterns['ď'] = '000101/000110/011100/100100/100100/100100/011100'.split('/')
    patterns['ť'] = '01001/01010/11100/01000/01000/01010/00100'.split('/')
    patterns['í'] = '001/010/000/010/010/010/010/010'.split('/')
    patterns['ý'] = '00010/00100/00000/10001/10001/01111/00001/01110'.split('/')
    patterns['³'] = '110/001/010/001/110/000/000'.split('/')
    for alias, base in {'−':'-', '–':'-', '—':'-', '\u00a0':' ', '℃':'C'}.items():
        patterns[alias] = patterns[base]
    glyphs = {}
    for char, rows in patterns.items():
        assert len(rows) <= 8 and all(len(row) == len(rows[0]) for row in rows), char
        glyphs[char] = [sum((row[x] == '1') << y for y, row in enumerate(rows)) for x in range(len(rows[0]))]
    return glyphs

